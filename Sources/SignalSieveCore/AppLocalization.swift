import Foundation

public enum AppLanguage: String, CaseIterable, Codable, Identifiable, Sendable {
    case english = "en"
    case spanish = "es"
    case norwegianBokmal = "nb"

    public var id: String { rawValue }

    public var displayName: String {
        switch self {
        case .english: "English"
        case .spanish: "Español"
        case .norwegianBokmal: "Norsk"
        }
    }

    /// Restores an explicit local choice and otherwise starts the app in English.
    public static func persistedOrEnglish(_ rawValue: String?) -> AppLanguage {
        rawValue.flatMap(AppLanguage.init(rawValue:)) ?? .english
    }

    fileprivate var localeIdentifier: String {
        switch self {
        case .english: "en_US"
        case .spanish: "es_MX"
        case .norwegianBokmal: "nb_NO"
        }
    }
}

public enum AppLocalization {
    public static func text(_ english: String, language: AppLanguage) -> String {
        guard language != .english else { return english }
        return translations[language]?[english] ?? english
    }

    public static func format(
        _ englishFormat: String,
        language: AppLanguage,
        _ arguments: CVarArg...
    ) -> String {
        String(
            format: text(englishFormat, language: language),
            locale: Locale(identifier: language.localeIdentifier),
            arguments: arguments
        )
    }

    public static func riskLabel(_ level: HiddenElementRiskLevel, language: AppLanguage) -> String {
        text(level.label, language: language)
    }

    public static func evidenceConfidenceLabel(
        _ confidence: EvidenceConfidence,
        language: AppLanguage
    ) -> String {
        text(confidence.rawValue, language: language)
    }

    public static func hiddenKind(_ kind: HiddenElementKind, language: AppLanguage) -> String {
        text(kind.rawValue, language: language)
    }

    public static func hiddenContext(
        _ context: HiddenElementContext,
        language: AppLanguage
    ) -> String {
        text(context.rawValue, language: language)
    }

    public static func codeKind(_ kind: CodeGuardFindingKind, language: AppLanguage) -> String {
        text(kind.rawValue, language: language)
    }

    public static func codeDetail(_ kind: CodeGuardFindingKind, language: AppLanguage) -> String {
        text(kind.detail, language: language)
    }

    public static func patternKind(_ kind: PatternFindingKind, language: AppLanguage) -> String {
        text(kind.rawValue, language: language)
    }

    public static func patternDetail(_ finding: PatternFinding, language: AppLanguage) -> String {
        switch finding.kind {
        case .repeatedPhrase:
            return format(
                "The same %d-word sequence appears in %d recent texts.",
                language: language,
                finding.pattern.split(separator: " ").count,
                finding.matchingSampleCount
            )
        case .repeatedOpening:
            return format(
                "Multiple sentences begin with this sequence across %d texts.",
                language: language,
                finding.matchingSampleCount
            )
        case .repeatedListStructure:
            return format(
                "%d recent texts use the same multi-item list structure.",
                language: language,
                finding.matchingSampleCount
            )
        case .repeatedPunctuation:
            return format(
                "This punctuation choice appears in %d recent texts.",
                language: language,
                finding.matchingSampleCount
            )
        }
    }

    public static func patternValue(_ finding: PatternFinding, language: AppLanguage) -> String {
        switch finding.kind {
        case .repeatedListStructure, .repeatedPunctuation:
            return text(finding.pattern, language: language)
        case .repeatedPhrase, .repeatedOpening:
            return finding.pattern
        }
    }

    public static func watermarkSignalDetail(
        _ signal: WatermarkProbeSignal,
        language: AppLanguage
    ) -> String {
        guard signal.isAvailable else {
            return text("This signal needs more sentences or words.", language: language)
        }
        let percent = Int((signal.observedValue * 100).rounded())
        switch signal.kind {
        case .repeatedNGrams:
            return format(
                "Repeated three-word sequence excess: %d%% of positions.",
                language: language,
                percent
            )
        case .lowLexicalDiversity:
            return format(
                "Average unique words in moving 50-word windows: %d%%.",
                language: language,
                percent
            )
        case .regularSentenceCadence:
            return format(
                "Sentence-length variation coefficient: %d%%.",
                language: language,
                percent
            )
        case .repeatedSentenceOpenings:
            return format(
                "Repeated two-word sentence openings: %d%%.",
                language: language,
                percent
            )
        }
    }

